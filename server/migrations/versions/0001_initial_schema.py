def _app_role() -> str:
    role = context.get_x_argument(as_dictionary=True).get("app_role", "pipe1_app")
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", role):
        raise ValueError(f"invalid app_role: {role!r}")
    return role


def _create_row_level_security() -> None:
    # Identity of the current request, set per transaction by
    # pipe1_server.db.set_access_context(). Unset or reset values read as NULL,
    # and every comparison with NULL fails, so no context means no rows.
    op.execute("""
        CREATE FUNCTION app_current_org() RETURNS uuid
        LANGUAGE sql STABLE
        AS $$ SELECT NULLIF(current_setting('app.org_id', true), '')::uuid $$
    """)
    op.execute("""
        CREATE FUNCTION app_current_user_id() RETURNS uuid
        LANGUAGE sql STABLE
        AS $$ SELECT NULLIF(current_setting('app.user_id', true), '')::uuid $$
    """)
    op.execute("""
        CREATE FUNCTION app_current_role() RETURNS text
        LANGUAGE sql STABLE
        AS $$ SELECT NULLIF(current_setting('app.role', true), '') $$
    """)
    # Same rule as the projects SELECT policy (docs/Web_Auth_Spec.md §2):
    # same organization, and the project is shared, owned by the user, or the
    # user is an org admin.
    op.execute("""
        CREATE FUNCTION app_can_access_project(p_project_id uuid) RETURNS boolean
        LANGUAGE sql STABLE
        AS $$
            SELECT EXISTS (
                SELECT 1 FROM inspection_projects p
                WHERE p.id = p_project_id
                  AND p.organization_id = app_current_org()
                  AND (p.visibility = 'org'
                       OR p.owner_user_id = app_current_user_id()
                       OR app_current_role() = 'org_admin')
            )
        $$
    """)

    op.execute("ALTER TABLE inspection_projects ENABLE ROW LEVEL SECURITY")
    op.execute("""
        CREATE POLICY projects_select ON inspection_projects FOR SELECT
        USING (organization_id = app_current_org()
               AND (visibility = 'org'
                    OR owner_user_id = app_current_user_id()
                    OR app_current_role() = 'org_admin'))
    """)
    op.execute("""
        CREATE POLICY projects_insert ON inspection_projects FOR INSERT
        WITH CHECK (organization_id = app_current_org()
                    AND owner_user_id = app_current_user_id())
    """)
    # Visibility changes and ownership transfer: owner or org admin. The WITH CHECK
    # stops an owner from handing the project to someone else; only admins transfer.
    op.execute("""
        CREATE POLICY projects_update ON inspection_projects FOR UPDATE
        USING (organization_id = app_current_org()
               AND (owner_user_id = app_current_user_id()
                    OR app_current_role() = 'org_admin'))
        WITH CHECK (organization_id = app_current_org()
                    AND (owner_user_id = app_current_user_id()
                         OR app_current_role() = 'org_admin'))
    """)
    op.execute("""
        CREATE POLICY projects_delete ON inspection_projects FOR DELETE
        USING (organization_id = app_current_org()
               AND (owner_user_id = app_current_user_id()
                    OR app_current_role() = 'org_admin'))
    """)

    for table in PROJECT_CHILD_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"""
            CREATE POLICY {table}_project_access ON {table} FOR ALL
            USING (app_can_access_project(project_id))
            WITH CHECK (app_can_access_project(project_id))
        """)


